# ANALYSIS COMPONENT: OUTPUTS (function library: manuscript numbers)
#
# Number plugging for the manuscript.
#
# results_numbers.Rmd registers every number cited in the text under a key
# (num(), num_ci()) and writes them all to one file, results/numbers.tex,
# which is uploaded to Overleaf. Each line is \nmdef{key}{value}; the
# manuscript cites a value with \nm{key}. Keys use dots and digits
# (post.hl.se080.med), which \newcommand names cannot, so the lookup goes
# through \csname (see the preamble block in write_numbers()).

NUMBERS <- new.env()

.num_fmt <- function(x, d) formatC(x, format = "f", digits = d, big.mark = ",")

# Register one value. Numbers are formatted to d decimal places; character
# values (country names, lists, whole tables) are stored as given. Returns the
# stored string so num() can sit inside an existing sprintf() call.
num <- function(key, value, d = 1) {
  if (!grepl("^[a-z0-9.]+$", key)) stop("Key '", key, "' must use lower-case letters, digits and dots only.")
  if (exists(key, envir = NUMBERS, inherits = FALSE)) warning("Key '", key, "' registered twice; keeping the last value.")
  if (length(value) != 1) stop("Key '", key, "' has ", length(value), " values; register one value per key.")
  if (is.numeric(value)) value <- .num_fmt(value, d)
  # An unescaped % starts a LaTeX comment and silently cuts the rest of the line
  if (grepl("(^|[^\\\\])%", value)) stop("Key '", key, "' contains an unescaped %.")
  assign(key, value, envir = NUMBERS)
  invisible(value)
}

# Integer counts (thousands separator, no decimals)
num_int <- function(key, value) num(key, round(value), d = 0)

# Median and interval: registers key.med, key.lo, key.hi, key.ci = "m (lo--hi)"
# and, with pct = TRUE, key.pci = "m\% (lo--hi)" (the regression paragraphs
# put the percent sign after the median only).
num_ci <- function(key, m, lo, hi, d = 1, pct = FALSE) {
  num(paste0(key, ".med"), m, d); num(paste0(key, ".lo"), lo, d); num(paste0(key, ".hi"), hi, d)
  num(paste0(key, ".ci"), sprintf("%s (%s--%s)", .num_fmt(m, d), .num_fmt(lo, d), .num_fmt(hi, d)))
  if (pct) num(paste0(key, ".pci"), sprintf("%s\\%% (%s--%s)", .num_fmt(m, d), .num_fmt(lo, d), .num_fmt(hi, d)))
  invisible(NULL)
}

# q3 vector c(median, 2.5%, 97.5%) as used throughout results_numbers.Rmd
num_q3 <- function(key, q, d = 1) num_ci(key, q[[1]], q[[2]], q[[3]], d)

# Whole LaTeX tables (character vector of lines) stored under tab.<name>
num_table <- function(key, lines) num(key, paste(lines, collapse = "\n"))

# Variant tags used in keys: RDT sensitivity 0.8 -> "se080"; sigma_d prior SD
# 0.05 -> "sd005"
se_key <- function(se) sprintf("se%03d", round(100 * se))
sd_key <- function(sd) sprintf("sd%03d", round(100 * sd))

# Every \nm{key} cited in the .tex files under manuscript_dir (recursive).
manuscript_keys <- function(manuscript_dir) {
  tex <- list.files(manuscript_dir, pattern = "\\.tex$", recursive = TRUE, full.names = TRUE)
  tex <- tex[basename(tex) != "numbers.tex"]
  txt <- unlist(lapply(tex, readLines, warn = FALSE))
  txt <- sub("(^|[^\\\\])%.*$", "\\1", txt)            # drop LaTeX comments
  sort(unique(unlist(regmatches(txt, gregexpr("(?<=\\\\nm\\{)[a-z0-9.]+(?=\\})", txt, perl = TRUE)))))
}

# keep: keys to write (default all registered keys).
write_numbers <- function(path, source_note = "", keep = NULL) {
  keys <- sort(ls(NUMBERS))
  if (!is.null(keep)) keys <- intersect(keys, keep)
  vals <- vapply(keys, function(k) get(k, envir = NUMBERS), "")
  header <- c(
    "% Generated by src/results_numbers.Rmd -- do not edit by hand.",
    sprintf("%% %s %s", format(Sys.time(), "%Y-%m-%d %H:%M"), source_note),
    "% Upload to Overleaf next to main.tex. Preamble needed in main.tex:",
    "%   \\usepackage{etoolbox}",
    "%   \\newcommand{\\nmdef}[2]{\\csdef{num.#1}{#2}}",
    "%   \\newcommand{\\nm}[1]{\\ifcsdef{num.#1}{\\csuse{num.#1}}{\\textcolor{red}{\\textbf{??\\detokenize{#1}}}\\PackageWarning{numbers}{Undefined number #1}}}",
    "%   \\InputIfFileExists{numbers.tex}{}{\\PackageWarning{numbers}{numbers.tex not found}}",
    sprintf("%% %d keys", length(keys)),
    "\\providecommand{\\nmdef}[2]{\\expandafter\\def\\csname num.#1\\endcsname{#2}}",
    "")
  writeLines(c(header, sprintf("\\nmdef{%s}{%s}", keys, vals)), path)
  invisible(path)
}
